using System.Text;
using Premise.Platform.Entitlements;
using Premise.Platform.Kernel;

// ADR 16: capability and entitlement keys generate from the C# catalogs into
// TS unions - one source of truth, two languages, no drift. Run via
// `pnpm codegen:keys` (or dotnet run) after changing either catalog.

var output = new StringBuilder();
output.AppendLine("// GENERATED by Premise.Tools.CodegenKeys - do not edit.");
output.AppendLine("// Source: Premise.Platform Capabilities + EntitlementCatalog.");
output.AppendLine();

output.AppendLine("export const CAPABILITIES = [");
foreach (var capability in Capabilities.All)
    output.AppendLine($"  '{capability}',");
output.AppendLine("] as const;");
output.AppendLine();
output.AppendLine("export type Capability = (typeof CAPABILITIES)[number];");
output.AppendLine();

output.AppendLine("export const ENTITLEMENTS = {");
foreach (var (code, descriptor) in EntitlementCatalog.Definitions.OrderBy(d => d.Key))
    output.AppendLine(
        $"  '{code}': {{ shape: '{descriptor.Shape}', policy: '{descriptor.Policy}', defaultValue: '{descriptor.DefaultValue}' }},"
    );
output.AppendLine("} as const;");
output.AppendLine();
output.AppendLine("export type EntitlementCode = keyof typeof ENTITLEMENTS;");

var root = AppContext.BaseDirectory;
string? repoRoot = null;
for (var dir = new DirectoryInfo(root); dir is not null; dir = dir.Parent)
    if (File.Exists(Path.Combine(dir.FullName, "Premise.slnx")))
    {
        repoRoot = dir.FullName;
        break;
    }
if (repoRoot is null)
{
    Console.Error.WriteLine("could not locate repo root (Premise.slnx)");
    return 1;
}
var target = Path.Combine(repoRoot, "web", "packages", "api", "src", "keys.ts");
Directory.CreateDirectory(Path.GetDirectoryName(target)!);
File.WriteAllText(target, output.ToString());
Console.WriteLine($"wrote {target}");
return 0;
